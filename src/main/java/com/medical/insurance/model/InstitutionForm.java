package com.medical.insurance.model;

public class InstitutionForm {

    private String institutionId;
    private String institutionName;
    private String hospitalLevel;
    private String institutionType;
    private String postcode;
    private String legalRepresentativeName;
    private String legalRepresentativeMobile;
    private String contactName;
    private String contactPhone;
    private String contactMobile;
    private String address;
    private String notes;

    public String getInstitutionId() { return institutionId; }
    public void setInstitutionId(String institutionId) { this.institutionId = institutionId; }
    public String getInstitutionName() { return institutionName; }
    public void setInstitutionName(String institutionName) { this.institutionName = institutionName; }
    public String getHospitalLevel() { return hospitalLevel; }
    public void setHospitalLevel(String hospitalLevel) { this.hospitalLevel = hospitalLevel; }
    public String getInstitutionType() { return institutionType; }
    public void setInstitutionType(String institutionType) { this.institutionType = institutionType; }
    public String getPostcode() { return postcode; }
    public void setPostcode(String postcode) { this.postcode = postcode; }
    public String getLegalRepresentativeName() { return legalRepresentativeName; }
    public void setLegalRepresentativeName(String legalRepresentativeName) { this.legalRepresentativeName = legalRepresentativeName; }
    public String getLegalRepresentativeMobile() { return legalRepresentativeMobile; }
    public void setLegalRepresentativeMobile(String legalRepresentativeMobile) { this.legalRepresentativeMobile = legalRepresentativeMobile; }
    public String getContactName() { return contactName; }
    public void setContactName(String contactName) { this.contactName = contactName; }
    public String getContactPhone() { return contactPhone; }
    public void setContactPhone(String contactPhone) { this.contactPhone = contactPhone; }
    public String getContactMobile() { return contactMobile; }
    public void setContactMobile(String contactMobile) { this.contactMobile = contactMobile; }
    public String getAddress() { return address; }
    public void setAddress(String address) { this.address = address; }
    public String getNotes() { return notes; }
    public void setNotes(String notes) { this.notes = notes; }
}
