package com.medical.insurance.model;

public class FacilityForm {

    private String serId;
    private String serName;
    private String serExpType;
    private String serStarttime;
    private String serEndtime;
    private String serValid;

    public String getSerId() { return serId; }
    public void setSerId(String serId) { this.serId = serId; }
    public String getSerName() { return serName; }
    public void setSerName(String serName) { this.serName = serName; }
    public String getSerExpType() { return serExpType; }
    public void setSerExpType(String serExpType) { this.serExpType = serExpType; }
    public String getSerStarttime() { return serStarttime; }
    public void setSerStarttime(String serStarttime) { this.serStarttime = serStarttime; }
    public String getSerEndtime() { return serEndtime; }
    public void setSerEndtime(String serEndtime) { this.serEndtime = serEndtime; }
    public String getSerValid() { return serValid; }
    public void setSerValid(String serValid) { this.serValid = serValid; }
}
